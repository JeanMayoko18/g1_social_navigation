"""
ROS4HRI TTS compatibility adapter.

Flow
----

dialogue_manager
    |
    | tts_msgs/action/TTS
    v
ROS4HRITTSAdapter
    |
    | g1_social_msgs/msg/ExplanationText
    v
/explainability/text
    |
    v
Speech Manager / Piper
    |
    | g1_social_msgs/msg/SpeechStatus
    v
ROS4HRITTSAdapter
    |
    +--> COMPLETED -> action succeeds
    +--> FAILED    -> action aborts
    +--> timeout   -> action aborts

Responsibilities
----------------

This node exposes the TTS action expected by ROS4HRI while keeping
the project speech architecture unchanged.

It does not synthesize or play audio. It publishes requests to the
Common Speech API and waits for the real SpeechStatus generated by
the single Speech Manager.

The adapter intentionally does not fabricate word-level feedback.
The current Common Speech API reports request lifecycle rather than
word timing.
"""

import threading
import time
import uuid
from typing import Dict, Optional

import rclpy
from g1_social_msgs.msg import ExplanationText, SpeechStatus
from rclpy.action import ActionServer, CancelResponse, GoalResponse
from rclpy.callback_groups import ReentrantCallbackGroup
from rclpy.executors import MultiThreadedExecutor
from rclpy.node import Node
from tts_msgs.action import TTS


class ROS4HRITTSAdapter(Node):
    """Bridge ROS4HRI TTS actions to the Common Speech API."""

    def __init__(self) -> None:
        super().__init__("ros4hri_tts_adapter")

        self.declare_parameter(
            "action_name",
            "tts_engine/tts",
        )
        self.declare_parameter(
            "speech_request_topic",
            "/explainability/text",
        )
        self.declare_parameter(
            "speech_status_topic",
            "/explainability/speech_status",
        )
        self.declare_parameter(
            "default_language",
            "en",
        )
        self.declare_parameter(
            "speech_timeout_sec",
            60.0,
        )

        self.action_name = str(
            self.get_parameter("action_name").value
        )
        self.speech_request_topic = str(
            self.get_parameter(
                "speech_request_topic"
            ).value
        )
        self.speech_status_topic = str(
            self.get_parameter(
                "speech_status_topic"
            ).value
        )
        self.default_language = str(
            self.get_parameter(
                "default_language"
            ).value
        ).strip().lower()
        self.speech_timeout_sec = float(
            self.get_parameter(
                "speech_timeout_sec"
            ).value
        )

        if not self.action_name:
            raise ValueError(
                "action_name cannot be empty."
            )

        if self.speech_timeout_sec <= 0.0:
            raise ValueError(
                "speech_timeout_sec must be positive."
            )

        self.callback_group = ReentrantCallbackGroup()

        self.speech_request_pub = self.create_publisher(
            ExplanationText,
            self.speech_request_topic,
            10,
        )

        self.speech_status_sub = self.create_subscription(
            SpeechStatus,
            self.speech_status_topic,
            self._speech_status_callback,
            10,
            callback_group=self.callback_group,
        )

        self._condition = threading.Condition()

        # decision_id -> latest SpeechStatus state
        self._states: Dict[str, str] = {}

        # decision_id -> diagnostic detail
        self._details: Dict[str, str] = {}

        self.action_server = ActionServer(
            self,
            TTS,
            self.action_name,
            execute_callback=self._execute_callback,
            goal_callback=self._goal_callback,
            cancel_callback=self._cancel_callback,
            callback_group=self.callback_group,
        )

        self.get_logger().info(
            "ROS4HRI TTS adapter ready: "
            f"action={self.action_name}, "
            f"request_topic={self.speech_request_topic}, "
            f"status_topic={self.speech_status_topic}"
        )

    def _goal_callback(
        self,
        goal_request: TTS.Goal,
    ) -> GoalResponse:
        text = str(goal_request.input).strip()

        if not text:
            self.get_logger().warn(
                "Rejecting empty TTS goal."
            )
            return GoalResponse.REJECT

        return GoalResponse.ACCEPT

    def _cancel_callback(
        self,
        _goal_handle,
    ) -> CancelResponse:
        # The current Common Speech API has no cancellation command.
        #
        # Do not claim that audio was canceled when the Speech Manager
        # cannot yet stop the corresponding queued/running request.
        self.get_logger().warn(
            "Rejecting TTS cancellation because the current "
            "Common Speech API has no speech cancellation contract."
        )
        return CancelResponse.REJECT

    def _speech_status_callback(
        self,
        msg: SpeechStatus,
    ) -> None:
        decision_id = str(msg.decision_id).strip()
        state = str(msg.state).strip().upper()

        if (
            not decision_id
            or state
            not in {
                "STARTED",
                "COMPLETED",
                "FAILED",
            }
        ):
            return

        with self._condition:
            self._states[decision_id] = state
            self._details[decision_id] = str(
                msg.detail
            ).strip()

            self._condition.notify_all()

    def _execute_callback(
        self,
        goal_handle,
    ) -> TTS.Result:
        result = TTS.Result()

        text = str(
            goal_handle.request.input
        ).strip()

        locale = str(
            goal_handle.request.locale
        ).strip()

        language = self._language_from_locale(
            locale
        )

        decision_id = (
            "ROS4HRI_TTS_"
            + uuid.uuid4().hex
        )

        request = ExplanationText()

        now = self.get_clock().now().to_msg()

        request.header.stamp = now
        request.decision_id = decision_id
        request.language = language
        request.text = text
        request.provider = "ros4hri"
        request.model = ""
        request.used_fallback = False
        request.used_cache = False
        request.speech_kind = "DIALOGUE"
        request.context_stamp = now
        request.navigation_state = ""
        request.navigation_goal_id = ""
        request.navigation_active = False
        request.social_conflict_active = False

        with self._condition:
            self._states.pop(
                decision_id,
                None,
            )
            self._details.pop(
                decision_id,
                None,
            )

        self.speech_request_pub.publish(
            request
        )

        self.get_logger().info(
            "Forwarded ROS4HRI TTS goal to "
            "Common Speech API: "
            f"decision_id={decision_id}"
        )

        terminal_state = self._wait_for_terminal_state(
            decision_id
        )

        if terminal_state == "COMPLETED":
            goal_handle.succeed()
            result.error_msg = ""

            self._forget_request(
                decision_id
            )

            return result

        if terminal_state == "FAILED":
            detail = self._get_detail(
                decision_id
            )

            goal_handle.abort()

            result.error_msg = (
                detail
                or "Speech Manager reported failure."
            )

            self._forget_request(
                decision_id
            )

            return result

        goal_handle.abort()

        result.error_msg = (
            "Timed out waiting for Speech Manager "
            "completion."
        )

        self._forget_request(
            decision_id
        )

        return result

    def _wait_for_terminal_state(
        self,
        decision_id: str,
    ) -> Optional[str]:
        deadline = (
            time.monotonic()
            + self.speech_timeout_sec
        )

        with self._condition:
            while True:
                state = self._states.get(
                    decision_id
                )

                if state in {
                    "COMPLETED",
                    "FAILED",
                }:
                    return state

                remaining = (
                    deadline
                    - time.monotonic()
                )

                if remaining <= 0.0:
                    return None

                self._condition.wait(
                    timeout=remaining
                )

    def _get_detail(
        self,
        decision_id: str,
    ) -> str:
        with self._condition:
            return self._details.get(
                decision_id,
                "",
            )

    def _forget_request(
        self,
        decision_id: str,
    ) -> None:
        with self._condition:
            self._states.pop(
                decision_id,
                None,
            )
            self._details.pop(
                decision_id,
                None,
            )

    def _language_from_locale(
        self,
        locale: str,
    ) -> str:
        locale = locale.strip().lower()

        if not locale:
            return self.default_language

        language = (
            locale
            .replace("-", "_")
            .split("_", maxsplit=1)[0]
        )

        if language in {"en", "es"}:
            return language

        self.get_logger().warn(
            "Unsupported TTS locale "
            f"'{locale}'. Falling back to "
            f"'{self.default_language}'."
        )

        return self.default_language

    def destroy_node(self) -> None:
        self.action_server.destroy()
        super().destroy_node()


def main(args=None) -> None:
    rclpy.init(args=args)

    node = ROS4HRITTSAdapter()

    executor = MultiThreadedExecutor(
        num_threads=4
    )
    executor.add_node(node)

    try:
        executor.spin()
    except KeyboardInterrupt:
        pass
    finally:
        executor.shutdown()
        node.destroy_node()
        rclpy.shutdown()


if __name__ == "__main__":
    main()